import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';

/**
 * generate `src/plugins/iconify-offline.generated.ts` — an inlined subset of every
 * iconify icon referenced anywhere in the repo (route metadata, mock menu data,
 * component templates), so the app renders icons with zero network access.
 *
 * usage: node scripts/gen-iconify-offline.mjs   (pnpm gen:icons)
 */

const ROOT = resolve(import.meta.dirname, '..');
const OUT_FILE = join(ROOT, 'src/plugins/iconify-offline.generated.ts');

const SCAN_DIRS = ['src', 'build', 'mock', 'scripts'];
const SCAN_EXT = new Set(['.ts', '.mts', '.mjs', '.js', '.vue', '.json', '.yaml', '.yml']);
const SKIP_DIRS = new Set(['node_modules', 'dist', 'iconify-offline.generated.ts']);

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      walk(full, files);
    } else {
      const dot = name.lastIndexOf('.');
      if (dot > 0 && SCAN_EXT.has(name.slice(dot))) files.push(full);
    }
  }
  return files;
}

/** collect `prefix:name` style icon references from all scanned sources */
function collectIconNames() {
  const names = new Set();
  const pattern = /\b([a-z0-9]+(?:-[a-z0-9]+)*):([a-z0-9]+(?:[-:][a-z0-9]+)*)\b/g;
  for (const dir of SCAN_DIRS) {
    const base = join(ROOT, dir);
    if (!existsSync(base)) continue;
    for (const file of walk(base)) {
      const text = readFileSync(file, 'utf8');
      for (const match of text.matchAll(pattern)) {
        names.add(`${match[1]}:${match[2]}`);
      }
    }
  }
  return names;
}

/** json file of an installed @iconify/json collection, null when the prefix is unknown */
function collectionFile(prefix) {
  const file = join(ROOT, 'node_modules/@iconify/json/json', `${prefix}.json`);
  return existsSync(file) ? file : null;
}

const names = collectIconNames();
const byPrefix = new Map();
let skipped = 0;

for (const name of [...names].sort()) {
  const [prefix, icon] = name.split(/:(.+)/);
  if (!collectionFile(prefix)) {
    skipped += 1;
    continue; // not an iconify reference (url scheme, css-like token, ...)
  }
  if (!byPrefix.has(prefix)) byPrefix.set(prefix, new Set());
  byPrefix.get(prefix).add(icon);
}

const collections = [];
for (const [prefix, icons] of [...byPrefix.entries()].sort()) {
  const data = JSON.parse(readFileSync(collectionFile(prefix), 'utf8'));
  const subset = { prefix, icons: {} };
  if (data.width) subset.width = data.width;
  if (data.height) subset.height = data.height;
  if (data.aliases) subset.aliases = {};

  const resolveIcon = name => {
    if (data.icons[name]) return { name, data: data.icons[name] };
    let alias = name;
    const seen = new Set();
    while (data.aliases?.[alias] && !seen.has(alias)) {
      seen.add(alias);
      if (data.aliases[alias].body) return { name, data: data.aliases[alias] };
      alias = data.aliases[alias].parent;
      if (data.icons[alias]) return { name, data: data.icons[alias], via: alias };
    }
    return null;
  };

  const unresolved = [];
  for (const icon of icons) {
    const hit = resolveIcon(icon);
    if (!hit) {
      unresolved.push(icon);
      continue;
    }
    if (hit.via) {
      subset.aliases[icon] = { parent: hit.via };
    } else {
      subset.icons[icon] = hit.data;
    }
  }
  if (unresolved.length) {
    console.warn(`[gen-icons] ${prefix}: not found -> ${unresolved.join(', ')}`);
  }
  if (Object.keys(subset.icons).length || Object.keys(subset.aliases || {}).length) {
    collections.push(subset);
  }
}

const header = `// generated by scripts/gen-iconify-offline.mjs — do not edit by hand.
// run \`pnpm gen:icons\` to regenerate after adding new iconify references.
/* eslint-disable */
`;
const body = `export const offlineIconifyCollections: Record<string, unknown>[] = ${JSON.stringify(collections)};
`;
writeFileSync(OUT_FILE, header + body);

const total = collections.reduce(
  (sum, item) => sum + Object.keys(item.icons).length + Object.keys(item.aliases || {}).length,
  0
);
console.log(
  `[gen-icons] ${total} icons from ${collections.length} collections -> ${resolve(ROOT, 'src/plugins/iconify-offline.generated.ts').replace(ROOT, '.')}`
);
console.log(`[gen-icons] collections: ${collections.map(item => item.prefix).join(', ')}`);
console.log(`[gen-icons] skipped ${skipped} non-iconify matches`);
